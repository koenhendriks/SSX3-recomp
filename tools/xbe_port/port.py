"""Build-variant support: let the PAL-addressed hand-written code build against another build of the game.

    python3 port.py XBE REPO OUTDIR

Hashes the XBE's .text section and looks for analysis/ports/*.json with that
text_sha256. Writes into OUTDIR:

  port_map.h          force-included into the hand-written sources (not the
                      generated code). Maps sub_PAL and sub_PAL_gen to the
                      build's names and defines VA_0x... for every VA(0x...) in
                      the hand-written code. With no matching port it is the
                      identity, which is the PAL build.
  icall_seeds.json    analysis/icall_seeds.json with each start ported.
  ssx3_overrides.c    src/ssx3_overrides.c with sub_ names ported, for
                      tools.recomp --exclude-manual to scan.

Prints the variant name ("pal" without a port). Stops with an error when the
hand-written code needs an address the port does not map: a guess would build
and then call the wrong function.
"""
import hashlib
import json
import pathlib
import re
import struct
import sys

HAND = ["src/*.c", "src/*.h", "src/vk/*.c", "src/web/*.c", "src/launcher/*.c"]
SUB = re.compile(r"\bsub_([0-9A-F]{8})(_gen)?\b")
VA = re.compile(r"\bVA\((0x[0-9A-Fa-f]{8})\)")
# Ranges the code tests against ("points into code", "looks like a vtable"). These
# are section bounds, not addresses of things, so a port gives them by name.
ABSENT = 0xFF000000
PAL_BOUNDS = {"CODE_END": 0x00280000, "VTABLE_LO": 0x00280000, "VTABLE_HI": 0x00340000,
              "OVERLAY_PAGE": 0x00290000}   # the 64 KB page of the in-game overlay screen vtables


def text_sha256(xbe_bytes):
    base = struct.unpack_from("<I", xbe_bytes, 0x104)[0]
    n, at = struct.unpack_from("<II", xbe_bytes, 0x11C)
    for i in range(n):
        _, _, _, raw, size, name_va = struct.unpack_from("<IIIIII", xbe_bytes, at - base + i * 56)
        o = name_va - base
        if xbe_bytes[o:xbe_bytes.index(b"\0", o)] == b".text":
            return hashlib.sha256(xbe_bytes[raw:raw + size]).hexdigest()
    raise SystemExit("XBE has no .text section")


def find_port(digest, ports_dir):
    """The port file for this .text, or None for PAL.

    A pal.json holding only PAL's text_sha256 makes an unknown build an error
    instead of a PAL build that links and then calls the wrong functions."""
    files = sorted(pathlib.Path(ports_dir).glob("*.json"))
    for f in files:
        port = json.loads(f.read_text())
        if port.get("text_sha256") == digest:
            return None if port.get("variant") == "pal" else port
    if any(f.name == "pal.json" for f in files):
        raise SystemExit(f"this XBE's .text (sha256 {digest}) matches no build in {ports_dir}: "
                         "not a known disc of SSX 3 (docs/PORTS.md)")
    return None


def port_lookup(port):
    """{PAL int: build int}, or None for the PAL build."""
    if port is None:
        return None
    m = {int(k, 16): int(v, 16) for k, v in port["map"].items()}
    # Things the build doesn't have (a screen it never shows): a value above guest
    # memory, so nothing compares equal to it, distinct per address for case labels.
    for a in port.get("absent", []):
        m[int(a, 16)] = ABSENT | (int(a, 16) & 0xFFFFFF)
    return m


def hand_sources(repo):
    for pat in HAND:
        yield from sorted(pathlib.Path(repo).glob(pat))


COMMENT_OR_STRING = re.compile(r'"(?:[^"\\\n]|\\.)*"|/\*.*?\*/|//[^\n]*', re.S)


def strip_comments(text):
    """C source without comments, so addresses named only in comments aren't required."""
    return COMMENT_OR_STRING.sub(lambda mo: mo.group(0) if mo.group(0).startswith('"') else " ", text)


def make_header(texts, m, variant, bounds=None, name="PAL"):
    """texts: source strings. m: lookup or None. bounds: the port's {name: int}, None for PAL.
    Returns (header text, missing PAL addresses and bound names)."""
    subs, vas = set(), set()
    for t in map(strip_comments, texts):
        subs.update(int(x, 16) for x, _ in SUB.findall(t))
        vas.update(int(x, 16) for x in VA.findall(t))
    missing = sorted(a for a in subs | vas if m is not None and a not in m)
    b = PAL_BOUNDS if m is None else (bounds or {})
    missing += sorted(set(PAL_BOUNDS) - set(b))
    out = [f"/* Generated by tools/xbe_port/port.py for the {variant} build. Do not edit. */",
           "#ifndef SSX3_PORT_MAP_H", "#define SSX3_PORT_MAP_H",
           f'#define SSX3_BUILD_VARIANT "{variant}"',
           f'#define SSX3_BUILD_NAME "{name}"',
           "#define VA(x) VA_##x"]
    for bound in sorted(PAL_BOUNDS):
        if bound in b:
            out.append(f"#define SSX3_{bound} 0x{b[bound]:08X}u")
    for a in sorted(vas):
        out.append(f"#define VA_0x{a:08X} 0x{(a if m is None else m.get(a, a)):08X}u")
    if m is not None:
        for a in sorted(subs):
            if a in m and m[a] != a:
                out.append(f"#define sub_{a:08X} sub_{m[a]:08X}")
                out.append(f"#define sub_{a:08X}_gen sub_{m[a]:08X}_gen")
    out.append("#endif")
    return "\n".join(out) + "\n", missing


def translate(text, m):
    """Rename sub_PAL to the build's name, for the recompiler's manual-function scan."""
    if m is None:
        return text
    def rep(mo):
        a = int(mo.group(1), 16)
        return f"sub_{m.get(a, a):08X}{mo.group(2) or ''}"
    return SUB.sub(rep, text)


def port_seeds(seeds, m):
    """Returns (ported seeds, PAL starts the port does not map)."""
    if m is None:
        return seeds, []
    out, dropped = [], []
    for s in seeds:
        a = int(s["start"], 16)
        if a in m:
            out.append(dict(s, start=f"0x{m[a]:08X}"))
        else:
            dropped.append(s["start"])
    return out, dropped


def main(xbe, repo, outdir):
    repo, outdir = pathlib.Path(repo), pathlib.Path(outdir)
    port = find_port(text_sha256(pathlib.Path(xbe).read_bytes()), repo / "analysis/ports")
    m = port_lookup(port)
    variant = port["variant"] if port else "pal"
    bounds = {k: int(v, 16) for k, v in port.get("bounds", {}).items()} if port else None
    name = port.get("name", variant) if port else "PAL"
    header, missing = make_header([f.read_text(errors="replace") for f in hand_sources(repo)], m, variant, bounds, name)
    if missing:
        raise SystemExit(f"port '{variant}' does not map {len(missing)} address(es) or bound(s) the code needs: "
                         + ", ".join(a if isinstance(a, str) else f"0x{a:08X}" for a in missing))
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "port_map.h").write_text(header)
    (outdir / "ssx3_overrides.c").write_text(translate((repo / "src/ssx3_overrides.c").read_text(errors="replace"), m))
    seeds, dropped = port_seeds(json.loads((repo / "analysis/icall_seeds.json").read_text()), m)
    (outdir / "icall_seeds.json").write_text(json.dumps(seeds, indent=2) + "\n")
    if dropped:
        print(f"warning: {len(dropped)} icall seed(s) have no {variant} address and were left out: "
              + ", ".join(dropped), file=sys.stderr)
    print(variant)


if __name__ == "__main__":
    main(*sys.argv[1:4])
